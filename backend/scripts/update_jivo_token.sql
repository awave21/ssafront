-- ============================================================================
-- Проверка результата обновления
-- ============================================================================
--
-- После выполнения UPDATE проверьте результат:

SELECT 
    c.id AS channel_id,
    ac.agent_id,
    c.jivo_provider_token,
    c.jivo_provider_id,
    c.jivo_reply_base_url,
    c.updated_at,
    a.name AS agent_name
FROM 
    channels c
LEFT JOIN 
    agent_channels ac ON c.id = ac.channel_id
LEFT JOIN
    agents a ON ac.agent_id = a.id
WHERE 
    c.type = 'jivo'
    AND c.is_deleted = false
    AND c.jivo_provider_token = 'новый-секретный-токен'  -- замените на ваш новый токен
ORDER BY 
    c.updated_at DESC;


