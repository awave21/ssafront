-- ============================================================================
-- Скрипт для обновления токена Jivo провайдера (jivo_provider_token)
-- ============================================================================
--
-- НАЗНАЧЕНИЕ:
--   Этот скрипт предназначен для обновления jivo_provider_token у существующего
--   Jivo канала в случаях:
--   - Компрометации текущего токена (утечка, несанкционированный доступ)
--   - Миграции канала на новые credentials
--   - Ротации токена в рамках политики безопасности
--   - Восстановления после сбоя интеграции
--
-- ВАЖНО:
--   - jivo_provider_token используется для аутентификации входящих webhook'ов от Jivo
--   - Токен также является частью URL для отправки исходящих сообщений
--   - После смены токена необходимо обновить webhook URL в настройках Jivo Bot API
--   - Токен должен быть уникальным (есть ограничение uq_channels_jivo_provider_token)
--
-- БЕЗОПАСНОСТЬ:
--   ✓ Скрипт использует явное WHERE условие для идентификации канала
--   ✓ Не содержит опасных операций (DROP, TRUNCATE, DELETE)
--   ✓ Использует транзакцию для атомарности операции
--   ✓ Проверяет количество затронутых строк
--
-- ============================================================================

-- Начинаем транзакцию для атомарности
BEGIN;

-- ============================================================================
-- ВАРИАНТ 1: Обновление токена по известному agent_id
-- ============================================================================
--
-- Используйте этот вариант, если известен ID агента, к которому привязан канал.
-- Это самый безопасный способ, так как он точно идентифицирует нужный канал.
--
-- ЗАМЕНИТЕ:
--   'ваш-agent-id-uuid' → реальный UUID агента из таблицы agents
--   'новый-секретный-токен' → новый уникальный токен (рекомендуется минимум 32 символа)
--
-- Пример запроса для поиска agent_id:
-- SELECT a.id, a.name, c.id AS channel_id, c.jivo_provider_token
-- FROM agents a
-- JOIN agent_channels ac ON a.id = ac.agent_id
-- JOIN channels c ON ac.channel_id = c.id
-- WHERE c.type = 'jivo' AND c.is_deleted = false;

UPDATE channels
SET 
    jivo_provider_token = 'новый-секретный-токен',
    updated_at = NOW()
WHERE 
    id IN (
        SELECT c.id
        FROM channels c
        JOIN agent_channels ac ON c.id = ac.channel_id
        WHERE 
            ac.agent_id = 'ваш-agent-id-uuid'::uuid
            AND c.type = 'jivo'
            AND c.is_deleted = false
    )
    AND type = 'jivo'
    AND is_deleted = false;

-- Проверяем, что обновлена ровно одна строка
DO $$
BEGIN
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Канал не найден. Проверьте agent_id и убедитесь, что канал типа jivo существует и не удален.';
    END IF;
END $$;


